"""BarrelTracker: boxes that persist over frames (Tanush's ask, 2026-11-06). BarrelViewer.fsm answers every frame on
its own; this program runs the same detector five times a second and shows a barrel only once it has been seen in
3 of the last 4 frames, keeps it through a missed frame, and forgets it after 4 misses in a row (barrels.tracker,
rule in its docstring). One-frame false boxes never appear; a barrel the segmentation drops for a frame does not
blink. The per-image answer itself is unchanged: `tm raw` overlays it in white for comparison.

Run (robot on, setup.zsh sourced, docs/RUNBOOK.md):

    cd barrels/live
    genfsm BarrelTracker.fsm         # writes BarrelTracker.py next to this file (only needed after editing the .fsm)
    simple_cli BarrelTracker

At the C> prompt:  tm seg | tm boxes | tm both   -> what to show (tracked boxes: yellow = orange barrel, green = blue)
                   tm raw                        -> also draw this frame's own boxes in white (again to hide them)
                   tm save / tm rec              -> raw frame(s) to snapshots/ (see barrel_live.py)
Quit with Ctrl+\\ before powering the robot off.

The state machine is BarrelViewer's with a 0.2 s loop and one more node (ToggleRaw). ShowFrame only works when
a new camera frame has arrived since the last tick, so the 3-of-4 count is over distinct frames.
"""
from aim_fsm import *
from barrel_live import BarrelLive
from barrels import tracker


class BarrelTracker(BarrelLive):
    def __init__(self):
        super().__init__()
        self.tracker = tracker.Tracker()      # TrackConfig(): 3 of the last 4 frames, overlap >= 0.3, forget after 4 misses
        self.show_raw = False

    class ShowFrame(StateNode):
        def start(self, event=None):
            super().start(event)
            program = self.parent
            image = program.new_frame()
            if image is None:
                return
            raw = program.hook.on_image(image)                 # this frame's own answer
            shown = program.tracker.update(raw)                # what the last frames agree on
            imshow("barrels (tracked)", program.hook.render(image, shown, program.mode, raw=raw if program.show_raw else None))
            program.report(shown)

    class ToggleRaw(StateNode):
        def start(self, event=None):
            super().start(event)
            self.parent.show_raw = not self.parent.show_raw
            print(f"BarrelTracker: per-frame boxes {'shown in white' if self.parent.show_raw else 'hidden'}")

    def setup(self):
        #         loop: self.ShowFrame() =T(0.2)=> loop
        #         loop =TM('boxes')=> self.SetMode('boxes') =N=> loop
        #         loop =TM('seg')=> self.SetMode('seg') =N=> loop
        #         loop =TM('both')=> self.SetMode('both') =N=> loop
        #         loop =TM('raw')=> self.ToggleRaw() =N=> loop
        #         loop =TM('save')=> self.Save() =N=> loop
        #         loop =TM('rec')=> self.Record() =N=> loop
        
        # Code generated by genfsm on Fri Nov  6 19:37:06 2026:
        
        loop = self.ShowFrame() .set_name("loop") .set_parent(self)
        setmode1 = self.SetMode('boxes') .set_name("setmode1") .set_parent(self)
        setmode2 = self.SetMode('seg') .set_name("setmode2") .set_parent(self)
        setmode3 = self.SetMode('both') .set_name("setmode3") .set_parent(self)
        toggleraw1 = self.ToggleRaw() .set_name("toggleraw1") .set_parent(self)
        save1 = self.Save() .set_name("save1") .set_parent(self)
        record1 = self.Record() .set_name("record1") .set_parent(self)
        
        timertrans1 = TimerTrans(0.2) .set_name("timertrans1")
        timertrans1 .add_sources(loop) .add_destinations(loop)
        
        textmsgtrans1 = TextMsgTrans('boxes') .set_name("textmsgtrans1")
        textmsgtrans1 .add_sources(loop) .add_destinations(setmode1)
        
        nulltrans1 = NullTrans() .set_name("nulltrans1")
        nulltrans1 .add_sources(setmode1) .add_destinations(loop)
        
        textmsgtrans2 = TextMsgTrans('seg') .set_name("textmsgtrans2")
        textmsgtrans2 .add_sources(loop) .add_destinations(setmode2)
        
        nulltrans2 = NullTrans() .set_name("nulltrans2")
        nulltrans2 .add_sources(setmode2) .add_destinations(loop)
        
        textmsgtrans3 = TextMsgTrans('both') .set_name("textmsgtrans3")
        textmsgtrans3 .add_sources(loop) .add_destinations(setmode3)
        
        nulltrans3 = NullTrans() .set_name("nulltrans3")
        nulltrans3 .add_sources(setmode3) .add_destinations(loop)
        
        textmsgtrans4 = TextMsgTrans('raw') .set_name("textmsgtrans4")
        textmsgtrans4 .add_sources(loop) .add_destinations(toggleraw1)
        
        nulltrans4 = NullTrans() .set_name("nulltrans4")
        nulltrans4 .add_sources(toggleraw1) .add_destinations(loop)
        
        textmsgtrans5 = TextMsgTrans('save') .set_name("textmsgtrans5")
        textmsgtrans5 .add_sources(loop) .add_destinations(save1)
        
        nulltrans5 = NullTrans() .set_name("nulltrans5")
        nulltrans5 .add_sources(save1) .add_destinations(loop)
        
        textmsgtrans6 = TextMsgTrans('rec') .set_name("textmsgtrans6")
        textmsgtrans6 .add_sources(loop) .add_destinations(record1)
        
        nulltrans6 = NullTrans() .set_name("nulltrans6")
        nulltrans6 .add_sources(record1) .add_destinations(loop)
        
        return self
