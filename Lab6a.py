from aim_fsm import *

class Lab6a(StateMachineProgram):
    def __init__(self):
        super().__init__(launch_path_viewer = True,
                         launch_particle_viewer = True,
                         speech = False)

    class PathToOrange(StateNode):
        def start(self, event=None):
            super().start(event)
            ob = self.robot.world_map.objects['OrangeBarrel.a']
            self.robot.path_planner.plan_path_this_process(self.robot, ob)
            self.robot.rrt.draw_path = self.robot.rrt.path
            print(self.robot.rrt.path)

    def setup(self):
        #         TagDetection(enabled=True) =N=> loop
        # 
        #         loop: Print("\n\nType 'tm' to proceed") =TM=> self.PathToOrange() =N=> loop
        
        # Code generated by genfsm on Wed Oct  7 00:38:27 2026:
        
        tagdetection1 = TagDetection(enabled=True) .set_name("tagdetection1") .set_parent(self)
        loop = Print("\n\nType 'tm' to proceed") .set_name("loop") .set_parent(self)
        pathtoorange1 = self.PathToOrange() .set_name("pathtoorange1") .set_parent(self)
        
        nulltrans1 = NullTrans() .set_name("nulltrans1")
        nulltrans1 .add_sources(tagdetection1) .add_destinations(loop)
        
        textmsgtrans1 = TextMsgTrans() .set_name("textmsgtrans1")
        textmsgtrans1 .add_sources(loop) .add_destinations(pathtoorange1)
        
        nulltrans2 = NullTrans() .set_name("nulltrans2")
        nulltrans2 .add_sources(pathtoorange1) .add_destinations(loop)
        
        return self
