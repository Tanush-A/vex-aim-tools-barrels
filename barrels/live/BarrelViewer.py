"""BarrelViewer: the detector's answer for each frame, on the robot's camera, live (Dave's ask, 2026-11-03).

Once a second: take the robot's current image, run the detector as it stands (frozen v1 segmentation + the
stripe-anchored detector), show the result in a window. Every frame is answered on its own, exactly as
tools/detect_image.py answers a photo; nothing downstream of the picture is touched (the world map still uses the
vendor detector). BarrelTracker.fsm is the same with boxes that persist over frames.

Run (robot on, setup.zsh sourced, docs/RUNBOOK.md):

    cd barrels/live
    genfsm BarrelViewer.fsm          # writes BarrelViewer.py next to this file (only needed after editing the .fsm)
    simple_cli BarrelViewer          # connects to $ROBOT and starts the machine

At the C> prompt:  tm seg | tm boxes | tm both   -> what to show (boxes is the default; yellow = orange barrel, green = blue)
                     (seg: the main window dims every pixel that is not a barrel color and a second window,
                      "<title> seg", shows only the segmented pixels; both: the same with the boxes)
                   tm save                       -> write the current raw frame to snapshots/robot_snapN.png
                   tm rec                        -> write every frame for ten seconds to snapshots/rec_<stamp>/
Quit with Ctrl+\\ before powering the robot off.

The state machine: ShowFrame grabs and shows a frame; `loop` re-enters it every second (=T(1)=>). A text message
(=TM('seg')=> etc.) detours through one of the shared nodes in barrel_live.py (SetMode, Save, Record) and comes
straight back (=N=>). All the image work is in the hook (barrels.worldmap_bridge.BarrelDetectorHook): RGB in,
drawn RGB out, the same code as the photo path.
"""
from aim_fsm import *
from barrel_live import BarrelLive


class BarrelViewer(BarrelLive):
    class ShowFrame(StateNode):
        def start(self, event=None):
            super().start(event)
            program = self.parent
            image = program.new_frame()
            if image is None:
                return
            program.show("barrels", program.hook.view(image, program.mode))
            program.report(program.hook.last_barrels)

    def setup(self):
        #         loop: self.ShowFrame() =T(1)=> loop
        #         loop =TM('boxes')=> self.SetMode('boxes') =N=> loop
        #         loop =TM('seg')=> self.SetMode('seg') =N=> loop
        #         loop =TM('both')=> self.SetMode('both') =N=> loop
        #         loop =TM('save')=> self.Save() =N=> loop
        #         loop =TM('rec')=> self.Record() =N=> loop
        
        # Code generated by genfsm on Wed Nov 11 20:24:15 2026:
        
        loop = self.ShowFrame() .set_name("loop") .set_parent(self)
        setmode1 = self.SetMode('boxes') .set_name("setmode1") .set_parent(self)
        setmode2 = self.SetMode('seg') .set_name("setmode2") .set_parent(self)
        setmode3 = self.SetMode('both') .set_name("setmode3") .set_parent(self)
        save1 = self.Save() .set_name("save1") .set_parent(self)
        record1 = self.Record() .set_name("record1") .set_parent(self)
        
        timertrans1 = TimerTrans(1) .set_name("timertrans1")
        timertrans1 .add_sources(loop) .add_destinations(loop)
        
        textmsgtrans1 = TextMsgTrans('boxes') .set_name("textmsgtrans1")
        textmsgtrans1 .add_sources(loop) .add_destinations(setmode1)
        
        nulltrans1 = NullTrans() .set_name("nulltrans1")
        nulltrans1 .add_sources(setmode1) .add_destinations(loop)
        
        textmsgtrans2 = TextMsgTrans('seg') .set_name("textmsgtrans2")
        textmsgtrans2 .add_sources(loop) .add_destinations(setmode2)
        
        nulltrans2 = NullTrans() .set_name("nulltrans2")
        nulltrans2 .add_sources(setmode2) .add_destinations(loop)
        
        textmsgtrans3 = TextMsgTrans('both') .set_name("textmsgtrans3")
        textmsgtrans3 .add_sources(loop) .add_destinations(setmode3)
        
        nulltrans3 = NullTrans() .set_name("nulltrans3")
        nulltrans3 .add_sources(setmode3) .add_destinations(loop)
        
        textmsgtrans4 = TextMsgTrans('save') .set_name("textmsgtrans4")
        textmsgtrans4 .add_sources(loop) .add_destinations(save1)
        
        nulltrans4 = NullTrans() .set_name("nulltrans4")
        nulltrans4 .add_sources(save1) .add_destinations(loop)
        
        textmsgtrans5 = TextMsgTrans('rec') .set_name("textmsgtrans5")
        textmsgtrans5 .add_sources(loop) .add_destinations(record1)
        
        nulltrans5 = NullTrans() .set_name("nulltrans5")
        nulltrans5 .add_sources(record1) .add_destinations(loop)
        
        return self
