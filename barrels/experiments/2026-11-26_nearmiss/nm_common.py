"""Shared by the scripts of experiment 2026-11-26_nearmiss (TODO C2): candidates by name, a per-frame cache, the
selection rule. TRAIN frames only: every image is read with ``judge.load_frame``, which refuses anything else.

A candidate is named by a short spec:

    fixed                 what runs today (the adopted color model)
    hyst:K                plain two-level thresholds: loose level K (1..5) kept when connected to strict pixels
    hystg:K               the same, and a loose pixel below the lowest strict pixel of its piece is not painted
    pc:S,B,MODE           partner-conditioned: stripe direction at level S (0..6, 6 = anything), body direction at
                          level B (0..7, 6 = darker than the ground, 7 = anything), 0 = off;
                          MODE = strict | pred | free (how far down and up loose body paint may go)
    pc:S,B,MODE;SWITCH    the same with one or more rules of the body direction off (for the ablation table):
                          noslot (own_slot), norun (runs_on), nocover (cover_min); separated by ";"

Every candidate builds its own mask and then calls ``detector.detect(mask)`` with the default ``DetConfig``.
"""
from __future__ import annotations

import hashlib
import json
import sys
from functools import lru_cache
from multiprocessing import Pool
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
BARRELS = HERE.parents[1]
sys.path.insert(0, str(BARRELS / "src"))
from barrels import conditions as cnd  # noqa: E402
from barrels import counting as ct  # noqa: E402
from barrels import detect_types as dtp  # noqa: E402
from barrels import detector as det  # noqa: E402
from barrels import geometry as geo  # noqa: E402
from barrels import hslabel as hl  # noqa: E402
from barrels import io  # noqa: E402
from barrels import judge as jg  # noqa: E402
from barrels import nearmiss as nm  # noqa: E402

CAM = geo.AIM_4A8B6118_BOXFIT
DET = det.DetConfig()
RESULTS = BARRELS / "results" / "2026-11-26_nearmiss"
CACHE = RESULTS / "cache"                       # ignored by git; regenerated by any script here
GROW = 4                                        # "outside the hand boxes" = outside every box grown by this many pixels


@lru_cache(maxsize=1)
def model():
    return hl.adopted_model()                   # the adopted color model (config eb863d84); never changed here


@lru_cache(maxsize=1)
def code_hash() -> str:
    """The cache is only valid for the code that wrote it: nearmiss.py and this file."""
    h = hashlib.sha1()
    for p in (BARRELS / "src" / "barrels" / "nearmiss.py", Path(__file__)):
        h.update(p.read_bytes())
    return h.hexdigest()[:10]


# ---------------------------------------------------------------- candidates by name

def parse(spec: str) -> tuple:
    kind, _, rest = spec.partition(":")
    if kind == "fixed" and not rest:
        return ("fixed",)
    if kind in ("hyst", "hystg"):
        return (kind, int(rest))
    if kind == "pc":
        main, *switches = rest.split(";")
        s, b, mode = main.split(",")
        off = {"noslot": {"own_slot": 2.0}, "norun": {"runs_on": 0.0}, "nocover": {"cover_min": 0.0}}
        kw = {}
        for sw in switches:
            if sw not in off:
                raise ValueError(f"unknown switch {sw!r} in {spec!r}")
            kw.update(off[sw])
        return ("pc", nm.NearMissConfig(stripe_level=int(s), body_level=int(b), bottom=mode, **kw))
    raise ValueError(f"unknown candidate {spec!r}")


def pc(s: int, b: int, mode: str = "strict") -> str:
    """The spec of a partner-conditioned candidate. With the body direction off the mode changes nothing: one name."""
    return f"pc:{s},{b},{mode if b else 'strict'}"


def mask_of(spec: str, frame, strict: np.ndarray | None = None) -> np.ndarray:
    """The class mask of a candidate on a frame. The picture is only read."""
    p = parse(spec)
    strict = nm.strict_mask(frame, model()) if strict is None else strict
    if p[0] == "fixed":
        return strict
    if p[0] in ("hyst", "hystg"):
        return nm.hysteresis_mask(frame, model(), p[1], guard_bottom=p[0] == "hystg", strict=strict)
    return nm.partner_mask(frame, model(), p[1], CAM, strict=strict)[0]


def describe(spec: str) -> str:
    p = parse(spec)
    if p[0] == "fixed":
        return "the fixed color model"
    if p[0] in ("hyst", "hystg"):
        lv = nm.LADDER[p[1]]
        return (f"two-level thresholds: loose = hue +-{lv.dh:g}, S -{lv.ds:g}, V >= {lv.v_min}, kept when connected to strict"
                + (", never below the lowest strict pixel of its piece" if p[0] == "hystg" else ""))
    c = p[1]

    def lv(v):
        rng = f"hue +-{v.dh:g}, S -{v.ds:g}, V >= {v.v_min}"
        return "off" if v.name == "off" else "anything" if v.anything else f"{rng}, or darker than {c.dark_ratio:g} x the ground" if v.kind == "dark" else rng
    return (f"partner-conditioned: stripe direction level {c.stripe_level} ({lv(nm.STRIPE_LADDER[c.stripe_level])}), body direction level "
            f"{c.body_level} ({lv(nm.BODY_LADDER[c.body_level])}), edges '{c.bottom}'" + ("".join("; " + x for x in spec.split(";")[1:])))


def detector_of(spec: str):
    """The candidate as a ``detect_frame(stem, frame) -> list[Barrel]`` for the judge."""
    parse(spec)

    def detect_frame(stem: str, frame) -> list:
        return det.detect(mask_of(spec, frame), DET, CAM)
    detect_frame.describe = f"{spec}: {describe(spec)}; then detector.detect with DetConfig defaults"
    detect_frame.spec = spec
    return detect_frame


# ---------------------------------------------------------------- frames and labels

@lru_cache(maxsize=1)
def frames() -> dict:
    """``judge.train_frames()``: train frames by the class of their condition. Test frames cannot get in."""
    return jg.train_frames()


def ordinary() -> list[str]:
    return list(frames()[cnd.ORDINARY])


def report_only() -> list[str]:
    return list(frames()[cnd.EXTREME]) + list(frames()[cnd.UNLISTED])


@lru_cache(maxsize=1)
def truth():
    return jg.load_truth(ordinary() + report_only())


def outside_boxes(shape, gts) -> np.ndarray:
    out = np.ones(shape, bool)
    for g in gts:
        x0, y0, x1, y1 = g.bbox
        out[max(0, y0 - GROW):y1 + GROW, max(0, x0 - GROW):x1 + GROW] = False
    return out


# ---------------------------------------------------------------- the per-frame cache

def _file(spec: str) -> Path:
    safe = spec.replace(":", "_").replace(",", "-").replace(";", "+")
    return CACHE / f"{code_hash()}__{safe}.json"


def work(args) -> tuple[str, dict]:
    """One frame, several candidates -> {spec: record}. A record: the state of every barrel and box (as the judge
    counts them), the boxes, and how much is painted inside and outside the hand boxes."""
    import cv2
    cv2.setNumThreads(1)
    stem, specs = args
    frame = jg.load_frame(stem)                                         # refuses anything but a train frame
    label = io.load_boxes(stem, check_image=False)
    gts = dtp.barrels_from_boxes(label)
    strict = nm.strict_mask(frame, model())
    outside = outside_boxes(strict.shape, gts)
    out = {}
    for spec in specs:
        mask = mask_of(spec, frame, strict)
        preds = det.detect(mask, DET, CAM)
        fc = ct.classify_frame(stem, preds, gts, bool(label.get("clean", True)))
        painted = mask != 0
        out[spec] = {"count": fc.to_dict(), "boxes": [[int(p.color), *(int(v) for v in p.bbox)] for p in preds],
                     "px_out": int((painted & outside).sum()), "px_in": int((painted & ~outside).sum()),
                     "px_added": int((mask != strict).sum())}
    return stem, out


def ensure(specs, stems, jobs: int = 8) -> dict[str, dict[str, dict]]:
    """{spec: {stem: record}} for these candidates on these frames, computed where the cache has none."""
    specs, stems = list(dict.fromkeys(specs)), list(stems)
    jg.require_train(stems)
    have = {}
    for spec in specs:
        p = _file(spec)
        have[spec] = json.loads(p.read_text()) if p.exists() else {}
    todo = {s: [spec for spec in specs if s not in have[spec]] for s in stems}
    todo = [(s, v) for s, v in todo.items() if v]
    if todo:
        if jobs > 1 and len(todo) > 1:
            with Pool(jobs) as pool:
                results = pool.map(work, todo, chunksize=2)
        else:
            results = [work(t) for t in todo]
        touched = set()
        for stem, recs in results:
            for spec, r in recs.items():
                have[spec][stem] = r
                touched.add(spec)
        CACHE.mkdir(parents=True, exist_ok=True)
        for spec in touched:
            _file(spec).write_text(json.dumps(have[spec]))
    return {spec: {s: have[spec][s] for s in stems} for spec in specs}


def counts_of(records: dict[str, dict]) -> dict[str, ct.FrameCount]:
    return {s: ct.FrameCount.from_dict(r["count"]) for s, r in records.items()}


def tally(records: dict[str, dict], stems) -> ct.Tally:
    stems = list(stems)
    return ct.tally(counts_of({s: records[s] for s in stems}), stems, truth().placements)


# ---------------------------------------------------------------- the selection rule (PREREG.md, "How a level is chosen")

def looseness(spec: str) -> tuple:
    """Smaller = closer to the fixed model. Ties in the selection go to the smaller one."""
    p = parse(spec)
    if p[0] == "fixed":
        return (0, 0, 0)
    if p[0] in ("hyst", "hystg"):
        return (p[1], 0, 0)
    return (p[1].stripe_level + p[1].body_level, p[1].body_level, nm.BOTTOM_MODES.index(p[1].bottom))


def choose(specs, train_stems, recs: dict | None = None, margins=None, jobs: int = 8) -> tuple[str, list[dict]]:
    """The setting for a fold, from the training frames only. Returns (the chosen spec, one row per setting).

    1. A setting is eligible when, on the training frames: it draws no more boxes on clean empty frames than the
       fixed model; and no training place finds fewer placements than under the fixed model by more than that
       place's margin (the judge's own margins).
    2. Among the eligible ones: the highest J = found - 2 x boxes that are not on their barrel (found per
       placement, boxes once per arrangement, as the judge counts them).
    3. Ties (J equal to 1e-6): the setting closest to the fixed model (``looseness``), then the first listed.
    The fixed model is always in the list and always eligible, so there is always an answer."""
    specs = list(dict.fromkeys(["fixed", *specs]))
    train_stems = list(train_stems)
    recs = recs or ensure(specs, train_stems, jobs)
    margins = margins or jg.load_margins()
    by_place = ct.group_stems(train_stems, "place")
    base = tally(recs["fixed"], train_stems)
    base_place = {p: tally(recs["fixed"], ss).found_w for p, ss in by_place.items()}
    rows = []
    for spec in specs:
        t = tally(recs[spec], train_stems)
        low = [p for p, ss in by_place.items() if tally(recs[spec], ss).found_w < base_place[p] - margins.for_place(p) - 1e-9]
        ok = t.clean_empty <= base.clean_empty and not low
        rows.append({"spec": spec, "found_w": t.found_w, "found": t.found, "extra_w": t.extra_w, "clean_empty": t.clean_empty,
                     "cluttered_empty_w": t.cluttered_empty_w, "J": t.found_w - 2 * t.extra_w, "eligible": ok, "places_low": low})
    best = None
    for r in rows:
        if not r["eligible"]:
            continue
        if best is None or r["J"] > best["J"] + 1e-6 or (abs(r["J"] - best["J"]) <= 1e-6 and looseness(r["spec"]) < looseness(best["spec"])):
            best = r
    return best["spec"], rows
