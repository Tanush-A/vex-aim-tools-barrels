from aim_fsm import *

class Lab6b(StateMachineProgram):
    def __init__(self):
        super().__init__(launch_path_viewer=True)

    class Go(StateNode):
        def start(self, event=None):
            super().start(event)
            ob = self.robot.world_map.objects['OrangeBarrel.a']
            self.post_data(ob)

    def setup(self):
        #         TagDetection(enabled=True) =N=> loop
        # 
        #         loop: Print("\n\nType 'tm' to proceed") =TM=> self.Go() =D=> pilot
        # 
        #         pilot: PilotToPose()
        #         pilot =C=> loop
        #         pilot =PILOT=> loop
        
        # Code generated by genfsm on Wed Oct  7 01:00:26 2026:
        
        tagdetection1 = TagDetection(enabled=True) .set_name("tagdetection1") .set_parent(self)
        loop = Print("\n\nType 'tm' to proceed") .set_name("loop") .set_parent(self)
        go1 = self.Go() .set_name("go1") .set_parent(self)
        pilot = PilotToPose() .set_name("pilot") .set_parent(self)
        
        nulltrans1 = NullTrans() .set_name("nulltrans1")
        nulltrans1 .add_sources(tagdetection1) .add_destinations(loop)
        
        textmsgtrans1 = TextMsgTrans() .set_name("textmsgtrans1")
        textmsgtrans1 .add_sources(loop) .add_destinations(go1)
        
        datatrans1 = DataTrans() .set_name("datatrans1")
        datatrans1 .add_sources(go1) .add_destinations(pilot)
        
        completiontrans1 = CompletionTrans() .set_name("completiontrans1")
        completiontrans1 .add_sources(pilot) .add_destinations(loop)
        
        pilottrans1 = PilotTrans() .set_name("pilottrans1")
        pilottrans1 .add_sources(pilot) .add_destinations(loop)
        
        return self
